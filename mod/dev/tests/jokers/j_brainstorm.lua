-- B10 Canio (growing, destroys cards)
local function destroy_faces()
    T.set_hand({ 'KS', 'QH', '7C', '5D', '3D', '2C', '4S', '6H' })
    T.use('hanged_man', { 'KS', 'QH' })
end
T.test('Hive Mind: copies vanilla Canio as Canio+ with the stored value, without gaining', function()
    run({ 'caino' }, { consumables = { 'hanged_man' } })
    destroy_faces()
    T.eq(T.joker('caino').ability.caino_xmult, 1 + 2, 'only the original grows (X1 per face)')
    T.eq(pair2().mult, 2 * 3 * 3)
end)
T.test('Hive Mind: copies Canio+ with its stored value, without gaining', function()
    run({ 'bplus_caino_plus' }, { consumables = { 'hanged_man' } })
    destroy_faces()
    T.eq(T.joker('bplus_caino_plus').ability.extra.Xmult, 1 + 2 * 2)
    T.eq(pair2().mult, 2 * 5 * 5)
end)

