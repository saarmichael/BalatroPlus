-- B5 Constellation (growing): the copy uses the stored value and never grows it
T.test('Hive Mind: copies vanilla Constellation with its stored value and does not grow it', function()
    run({ 'constellation' }, { consumables = { 'venus', 'earth', 'mars' }, consumable_slots = 3 })
    T.use('venus'); T.use('earth')
    -- vanilla Constellation gained 0.1 per Planet: X1.2. The copy gained nothing.
    near(T.joker('constellation').ability.x_mult, 1 + 0.1 * 2)
    T.set_hand({ '2S', '2H', '7C', '9D', '3D' })
    near(T.play({ '2S', '2H' }).mult, 2 * (1 + 0.1 * 2) * (1 + 0.1 * 2))
    T.use('mars')
    near(T.joker('constellation').ability.x_mult, 1 + 0.1 * 3, 'one more Planet: only the original grows')
end)
T.test('Hive Mind: copies Galaxy with its stored value and does not grow it', function()
    run({ 'bplus_constellation_plus' }, { consumables = { 'venus', 'earth', 'mars' }, consumable_slots = 3 })
    T.use('venus'); T.use('earth')
    near(T.joker('bplus_constellation_plus').ability.extra.Xmult, 1 + 0.2 * 2)
    T.set_hand({ '2S', '2H', '7C', '9D', '3D' })
    near(T.play({ '2S', '2H' }).mult, 2 * (1 + 0.2 * 2) * (1 + 0.2 * 2))
    T.use('mars')
    near(T.joker('bplus_constellation_plus').ability.extra.Xmult, 1 + 0.2 * 3)
end)

