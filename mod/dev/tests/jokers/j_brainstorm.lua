local T = BPlus.test

-- Hive Mind copies the UPGRADED ability of the leftmost joker (D23). Every lineup below is { target, others... };
-- the target goes first, Hive Mind goes last.
local COPIER = 'bplus_brainstorm_plus'
local function lineup(parts)
    local out = {}
    for _, p in ipairs(parts) do out[#out + 1] = p end
    out[#out + 1] = COPIER
    return out
end
local function run(parts, extra)
    local s = { jokers = lineup(parts), ante = 3 }
    for k, v in pairs(extra or {}) do s[k] = v end
    T.start_run(s)
    T.select_blind()
end
local function pair2()
    T.set_hand({ '2S', '2H', '7C', '9D', '3D' })
    return T.play({ '2S', '2H' })
end
local function compat()
    T.wait_frames(4)
    return T.joker(COPIER).ability.blueprint_compat
end
local function near(a, e, what) T.near(a, e, 1e-6, what) end

-- B1 Jolly: +8 Mult per Pair, "+" +20
T.test('Hive Mind: copies the "+" ability of vanilla Jolly Joker (+20, not +8)', function()
    run({ 'jolly' })
    T.eq(compat(), 'compatible')
    -- Pair of 2s: 10 + 2 + 2 chips; Mult 2 + own +8 + copy +20
    local r = pair2()
    T.eq(r.chips, 10 + 2 + 2)
    T.eq(r.mult, 2 + 8 + 20)
end)
T.test('Hive Mind: copies Merry Joker as it is', function()
    run({ 'bplus_jolly_plus' })
    T.eq(pair2().mult, 2 + 20 + 20)
end)

-- B2 Faceless: $5 for 3 faces discarded, "+" $6
