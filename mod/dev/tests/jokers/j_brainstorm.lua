    T.discard({ 'KS', 'QH', 'JD' })
    T.eq(G.GAME.dollars, 6 + 6)
end)

-- B3 Ancient: X1.5 per card of the Ur-Joker suit, vanilla X1.5 per card of the Ancient suit
T.test('Hive Mind: copies the "+" ability of vanilla Ancient Joker (Ur-Joker suit)', function()
    run({ 'ancient' })
    G.GAME.current_round.bplus_ur_card.suit = 'Hearts'
    G.GAME.current_round.ancient_card.suit = 'Spades'
    T.set_hand({ 'KH', '2C', '3C', '5C', '7D' })
    -- the copy scores X1.5 for the Heart; the vanilla Ancient (Spades) does nothing
    T.eq(T.play({ 'KH' }).mult, 1 * 1.5)
end)
T.test('Hive Mind: copies Ur-Joker as it is', function()
    run({ 'bplus_ancient_plus' })
    G.GAME.current_round.bplus_ur_card.suit = 'Hearts'
    T.set_hand({ 'KH', '2C', '3C', '5C', '7D' })
    T.eq(T.play({ 'KH' }).mult, 1 * 1.5 * 1.5)
end)

-- B4 Scholar: Aces +20 Chips +4 Mult, "+" +40 / +10
