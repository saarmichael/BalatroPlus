-- B7 Green Joker (growing and shrinking)
T.test('Hive Mind: copies vanilla Green Joker as Evergreen (stored value, no growth from the copy)', function()
    run({ 'green_joker' }, { hands = 5 })
    -- hand 1: Green gains +1 (stored 1); own +1, copy +1
    T.eq(pair2().mult, 2 + 1 + 1)
    T.eq(T.joker('green_joker').ability.mult, 1)
    T.eq(pair2().mult, 2 + 2 + 2)
    T.eq(T.joker('green_joker').ability.mult, 2, 'the copy did not gain')
end)
T.test('Hive Mind: copies Evergreen Joker (no growth from the copy)', function()
    run({ 'bplus_green_joker_plus' }, { hands = 5 })
    T.eq(pair2().mult, 2 + 2 + 2)
    T.eq(T.joker('bplus_green_joker_plus').ability.extra.mult, 2)
    T.eq(pair2().mult, 2 + 4 + 4)
    T.eq(T.joker('bplus_green_joker_plus').ability.extra.mult, 4)
end)

-- B8 Seance: card creation through the copy
local function spectrals()
    local n = 0
    for _, c in ipairs(G.consumeables.cards) do if c.ability.set == 'Spectral' then n = n + 1 end end
    return n
end
T.test('Hive Mind: copies the "+" ability of vanilla Seance (2 Spectrals from the copy + 1 own)', function()
    run({ 'seance' }, { consumable_slots = 4 })
    T.set_hand({ '9S', '8S', '7S', '6S', '5S' })
    T.eq(T.play({ '9S', '8S', '7S', '6S', '5S' }).hand, 'Straight Flush')
    T.eq(spectrals(), 2 + 1)
end)
T.test('Hive Mind: copies Spirit Board as it is (2 + 2 Spectrals)', function()
    run({ 'bplus_seance_plus' }, { consumable_slots = 4 })
    T.set_hand({ '9S', '8S', '7S', '6S', '5S' })
    T.play({ '9S', '8S', '7S', '6S', '5S' })
    T.eq(spectrals(), 2 + 2)
end)

-- B9 Sock and Buskin (retriggers); Oops! All 6s makes the "+" chance certain
