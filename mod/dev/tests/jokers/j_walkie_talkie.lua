    T.eq(r.chips, 5 + 7)
    T.eq(r.mult, 1)
end)

T.test('Ham Radio: vanilla forced to "+" matches (vanilla 1 + 4, "+" 1 + 4 mult)', function()
    T.start_run({ jokers = { 'walkie_talkie' }, ante = 3 })
    T.select_blind()
    T.set_hand({ '10S', '9C', '6D', '3H', '2S' })
    T.force_behavior('walkie_talkie', 'plus')
    local r = T.play({ '10S' })
    T.eq(r.chips, 5 + 10 + 100)
    T.eq(r.mult, 1 + 4)
end)

T.test('Ham Radio: vanilla not forced keeps vanilla numbers', function()
