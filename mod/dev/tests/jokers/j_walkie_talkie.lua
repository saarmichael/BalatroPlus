end)

T.test('Ham Radio: scoring a 7 -> no effect', function()
    T.start_run({ jokers = { 'bplus_walkie_talkie_plus' }, ante = 3 })
    T.select_blind()
    T.set_hand({ '7S', '9C', '6D', '3H', '2S' })
